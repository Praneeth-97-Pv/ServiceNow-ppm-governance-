var PASS=0, FAIL=0;
function check(l,c,d){ if(c){PASS++;gs.print('  PASS  '+l+(d?'  ['+d+']':''));} else {FAIL++;gs.print('  FAIL  '+l+(d?'  ['+d+']':''));} }

var DID='0adc9ea6db40481025c85a35dc9619e8';
var GID='52470e6383de4b10b5ea5e65eeaad3ce';

gs.print('===== what the M0 button does: set approval=requested, save =====');
var d=new GlideRecord('dmn_demand'); d.get(DID);
gs.print('  ' + d.getValue('number') + ' before: approval=' + d.getValue('approval') + ' m0_state=' + d.getValue('u_m0_state'));
d.approval='requested';
d.update();
var d2=new GlideRecord('dmn_demand'); d2.get(DID);
check('Approval held at requested', (d2.getValue('approval')+'')==='requested', d2.getValue('approval'));
check('M0 state set to open', (d2.getValue('u_m0_state')+'')==='open', d2.getValue('u_m0_state'));
var names=[];
var a=new GlideRecord('sysapproval_approver');
a.addQuery('document_id',DID); a.addQuery('source_table','dmn_demand'); a.query();
while(a.next()){ names.push(a.approver.getDisplayValue()+'/'+a.getValue('state')); }
gs.print('  approvers: ' + names.join(', '));
check('Approvers generated by the save', names.length===2, names.length+' created');

gs.print('');
gs.print('===== UI action conditions evaluate =====');
var ua=new GlideRecord('sys_ui_action');
ua.addEncodedQuery('tableINu_pm_gates,project_change_request,dmn_demand^nameLIKERequest^nameNOT LIKEPurchase');
ua.query();
while(ua.next()){
  var cond = ua.getValue('condition');
  var rec, tbl = ua.getValue('table');
  if (tbl=='dmn_demand'){ rec=new GlideRecord('dmn_demand'); rec.get(DID); }
  else if (tbl=='u_pm_gates'){ rec=new GlideRecord('u_pm_gates'); rec.get(GID); }
  else { rec=new GlideRecord('project_change_request'); rec.addEncodedQuery('parentISNOTEMPTY'); rec.setLimit(1); rec.query(); rec.next(); }
  var current = rec;
  var ok, err='';
  try { ok = eval(cond); } catch(e){ ok='ERROR'; err=e+''; }
  gs.print('  ' + tbl + ' / ' + ua.getValue('name') + ' -> condition=' + ok + (err?' ('+err+')':''));
  check(tbl + ' button condition is valid JS', ok !== 'ERROR', String(ok));
}

gs.print('');
gs.print('===== cleanup =====');
var g=new GlideRecord('u_pm_gates'); if(g.get(GID)){ g.deleteRecord(); gs.print('  deleted preview test gate'); }
var rd=new GlideRecord('dmn_demand'); rd.get(DID);
rd.approval='not requested'; rd.setWorkflow(false); rd.update();
var cl=new GlideRecord('sysapproval_approver'); cl.addQuery('document_id',DID); cl.query();
var n=0; while(cl.next()){ cl.deleteRecord(); n++; }
gs.print('  reset ' + rd.getValue('number') + ' and removed ' + n + ' approver record(s)');

gs.print('');
gs.print('  PASS: '+PASS+'   FAIL: '+FAIL);
